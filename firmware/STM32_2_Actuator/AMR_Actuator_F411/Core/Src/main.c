/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_ADC1_Init();
  MX_TIM1_Init();
  MX_TIM2_Init();
  MX_TIM4_Init();
  MX_USB_DEVICE_Init();
  /* USER CODE BEGIN 2 */
  Actuator_Init(&htim1, &htim4);

  FSR_Init(&hadc1);

  HCSR04_Init(&htim2);

  Mechanism_Init();

  Communication_Init();


  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */

	    /* =====================================================
	     * STATE MACHINE CHÍNH
	     * ===================================================== */

	     Mechanism_Task();

	     Communication_Task();


	    /* =====================================================
	     * DEBUG / TELEMETRY
	     * ===================================================== */

	    g_mech_fsr =
	        Mechanism_GetFSR();

	    g_mech_distance =
	        Mechanism_GetDistance();

	    g_mech_state =
	        (uint8_t)Mechanism_GetState();

	    g_mech_fault =
	        (uint8_t)Mechanism_GetFault();

	    g_mech_hcsr_valid =
	        HCSR04_IsValid();

	    g_mech_hcsr_error =
	        HCSR04_GetError();

	    g_mech_echo_us =
	        HCSR04_GetPulseUs();


	    /* =====================================================
	     * COMMAND 1 = OPEN
	     * ===================================================== */

	    if (g_mech_cmd == 1)
	    {
	        g_mech_cmd = 0;

	        Mechanism_StartOpen();
	    }


	    /* =====================================================
	     * COMMAND 2 = PICK
	     *
	     * Đóng kẹp -> FSR đủ lực
	     * -> nâng -> TOP
	     * ===================================================== */

	    else if (g_mech_cmd == 2)
	    {
	        g_mech_cmd = 0;

	        Mechanism_StartPick();
	    }

	    else if (g_mech_cmd == 6)
	    {
	        g_mech_cmd = 0;

	        Mechanism_StartClose();
	    }
	    /* =====================================================
	     * COMMAND 3 = DROP
	     *
	     * Hạ -> BOTTOM
	     * -> mở kẹp
	     * ===================================================== */

	    else if (g_mech_cmd == 3)
	    {
	        g_mech_cmd = 0;

	        Mechanism_StartDrop();
	    }


	    /* =====================================================
	     * COMMAND 4 = TEST CHỈ NÂNG
	     * Không đụng cơ cấu kẹp
	     * ===================================================== */

	    else if (g_mech_cmd == 4)
	    {
	        uint32_t test_start;

	        g_mech_cmd = 0;

	        Mechanism_Stop();
	        Lift_Stop();
	        test_start = HAL_GetTick();

	        while ((HAL_GetTick() - test_start) < LIFT_UP_TIME_MS)
	        {
	            Lift_Up(LIFT_PWM_DEFAULT);
	            HAL_Delay(50);
	        }

	        Lift_Stop();
	    }


	    /* =====================================================
	     * COMMAND 5 = TEST CHỈ HẠ
	     * Không mở kẹp
	     * ===================================================== */

	    else if (g_mech_cmd == 5)
	    {
	        uint32_t test_start;

	        g_mech_cmd = 0;

	        Mechanism_Stop();
	        Lift_Stop();
	        test_start = HAL_GetTick();

	        while ((HAL_GetTick() - test_start) < LIFT_DOWN_FULL_TIME_MS)
	        {
	            Lift_Down(LIFT_PWM_DEFAULT);
	            HAL_Delay(50);
	        }

	        Lift_Stop();
	    }


	    /* =====================================================
	     * COMMAND 9 = STOP
	     * ===================================================== */

	    else if (g_mech_cmd == 9)
	    {
	        g_mech_cmd = 0;

	        Mechanism_Stop();

	        Actuator_StopAll();
	    }


	    /* =====================================================
	     * COMMAND 20 = RESET FAULT
	     * ===================================================== */

	    else if (g_mech_cmd == 20)
	    {
	        g_mech_cmd = 0;

	        Mechanism_ResetFault();
	    }


	    /* =====================================================
	     * COMMAND 21 = SAFE RECOVER OPEN
	     *
	     * Only accepted by Mechanism_StartRecoverOpen() for
	     * clamp-related faults (OVER_FORCE / CLAMP_TIMEOUT).
	     * ===================================================== */

	    else if (g_mech_cmd == 21)
	    {
	        g_mech_cmd = 0;

	        (void)Mechanism_StartRecoverOpen();
	    }


	    HAL_Delay(2);


  }
}
